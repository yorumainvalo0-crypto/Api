import { chmodSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

/**
 * Appended to Claude Code's built-in system prompt for sessions started from the app terminal.
 * Must stay free of `"`, `%` and `!` so it can be embedded verbatim in a .cmd file.
 */
export const TERMINAL_SYSTEM_NOTE =
  "You are running in the terminal of the AI Workbench desktop app on the user's own computer. " +
  "Reply in the user's language (usually German); keep code, identifiers and code comments in English. " +
  'The app may confine you to the folder the terminal was opened in: if a tool call is blocked for ' +
  'that reason, tell the user and do not try to work around it.'

/**
 * Variables the terminal sets for the wrapper. The OTLP ones are turned into OpenTelemetry
 * settings for `claude` only (not for the shell), so the app receives per-request token and cost
 * events on its local endpoint.
 */
export const WRAPPER_ENV = {
  /** Runtime path; on Windows read from the environment because cmd decodes .cmd files in the
   * console code page, which would break non-ASCII user names in the path. */
  claude: 'AIW_CLAUDE_EXE',
  endpoint: 'AIW_OTEL_ENDPOINT',
  token: 'AIW_OTEL_TOKEN',
  session: 'AIW_TERMINAL_SESSION',
  /** Per-session settings file (work folder confinement), passed with --settings. */
  settings: 'AIW_CLAUDE_SETTINGS',
  /** Permission mode from the app settings, passed with --permission-mode. */
  permissionMode: 'AIW_PERMISSION_MODE',
} as const

/** Settings applied to `claude` when the app's usage endpoint is set (values may use the env). */
function telemetryVars(ref: (name: string) => string): [string, string][] {
  return [
    ['CLAUDE_CODE_ENABLE_TELEMETRY', '1'],
    ['OTEL_LOGS_EXPORTER', 'otlp'],
    ['OTEL_METRICS_EXPORTER', 'none'],
    ['OTEL_TRACES_EXPORTER', 'none'],
    ['OTEL_EXPORTER_OTLP_LOGS_PROTOCOL', 'http/json'],
    ['OTEL_EXPORTER_OTLP_LOGS_ENDPOINT', ref(WRAPPER_ENV.endpoint)],
    ['OTEL_EXPORTER_OTLP_LOGS_HEADERS', `Authorization=Bearer ${ref(WRAPPER_ENV.token)}`],
    ['OTEL_RESOURCE_ATTRIBUTES', `aiw.terminal=${ref(WRAPPER_ENV.session)}`],
    ['OTEL_LOGS_EXPORT_INTERVAL', '1000'],
  ]
}

export interface WrapperFile {
  name: string
  content: string
  /** File mode on POSIX. */
  mode: number
}

/** Quotes a string for POSIX sh (single quotes, embedded quotes escaped). */
export function shQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`
}

/** Escapes a path for a quoted value in a .cmd file; `%` would start a variable reference. */
function cmdEscape(value: string): string {
  if (value.includes('"')) throw new Error(`Ungültiges Zeichen im Pfad: ${value}`)
  return value.replace(/%/g, '%%')
}

/**
 * The `claude` command for the terminal: runs the bundled Claude Code runtime with the
 * AI Workbench note appended to its system prompt, the session's settings file and permission
 * mode (when the terminal set them) and passes all user arguments through; a
 * `--permission-mode` typed by the user comes later and wins.
 * A .cmd file on Windows (works from PowerShell and cmd, unlike a .ps1 under the default
 * execution policy), a POSIX sh script elsewhere.
 */
export function claudeWrapper(claudePath: string, platform: NodeJS.Platform): WrapperFile {
  if (platform === 'win32') {
    const lines = [
      '@echo off',
      'rem Generated by AI Workbench: runs the bundled Claude Code with the app settings.',
      'setlocal',
      `if not defined ${WRAPPER_ENV.claude} set "${WRAPPER_ENV.claude}=${cmdEscape(claudePath)}"`,
      'set "AIW_MODE_FLAG="',
      `if defined ${WRAPPER_ENV.permissionMode} set "AIW_MODE_FLAG=--permission-mode %${WRAPPER_ENV.permissionMode}%"`,
      `if not defined ${WRAPPER_ENV.endpoint} goto run`,
      ...telemetryVars((name) => `%${name}%`).map(([key, value]) => `set "${key}=${value}"`),
      ':run',
      // Paths come from the environment (see WRAPPER_ENV.claude), so non-ASCII names survive.
      `if defined ${WRAPPER_ENV.settings} goto confined`,
      `"%${WRAPPER_ENV.claude}%" --append-system-prompt "${TERMINAL_SYSTEM_NOTE}" %AIW_MODE_FLAG% %*`,
      'exit /b %ERRORLEVEL%',
      ':confined',
      `"%${WRAPPER_ENV.claude}%" --append-system-prompt "${TERMINAL_SYSTEM_NOTE}" --settings "%${WRAPPER_ENV.settings}%" %AIW_MODE_FLAG% %*`,
      'exit /b %ERRORLEVEL%',
    ]
    return { name: 'claude.cmd', content: `${lines.join('\r\n')}\r\n`, mode: 0o644 }
  }
  const lines = [
    '#!/bin/sh',
    '# Generated by AI Workbench: runs the bundled Claude Code with the app settings.',
    `if [ -n "$${WRAPPER_ENV.endpoint}" ]; then`,
    ...telemetryVars((name) => `$${name}`).map(([key, value]) => `  export ${key}="${value}"`),
    'fi',
    `if [ -n "$${WRAPPER_ENV.permissionMode}" ]; then`,
    `  set -- --permission-mode "$${WRAPPER_ENV.permissionMode}" "$@"`,
    'fi',
    `if [ -n "$${WRAPPER_ENV.settings}" ]; then`,
    `  set -- --settings "$${WRAPPER_ENV.settings}" "$@"`,
    'fi',
    `exec ${shQuote(claudePath)} --append-system-prompt ${shQuote(TERMINAL_SYSTEM_NOTE)} "$@"`,
  ]
  return { name: 'claude', content: `${lines.join('\n')}\n`, mode: 0o755 }
}

/** Writes the wrapper into `binDir` (only when it changed) and returns its path. */
export function installClaudeWrapper(
  binDir: string,
  claudePath: string,
  platform: NodeJS.Platform = process.platform,
): string {
  const wrapper = claudeWrapper(claudePath, platform)
  const file = join(binDir, wrapper.name)
  mkdirSync(binDir, { recursive: true })
  let current: string | undefined
  try {
    current = readFileSync(file, 'utf8')
  } catch {
    current = undefined
  }
  if (current !== wrapper.content) writeFileSync(file, wrapper.content, { mode: wrapper.mode })
  if (platform !== 'win32') chmodSync(file, wrapper.mode)
  return file
}
